-- bd 十二张独立业务表：首次执行，空表初始化，不迁移旧数据。
-- 执行前请设置 search_path，与服务及 Spark 元数据库配置一致。
-- PostgreSQL / GaussDB-compatible metadata tables. Run in the metadata schema.
-- Set search_path to the same schema used by service and Spark before execution.
-- Creates EMPTY tables only. Existing old tables and data are untouched.
BEGIN;

CREATE TABLE TSS_BCOMP_CONF_NEW (
    BCOMP_INDEX BIGINT PRIMARY KEY,
    BCOMP_NAME VARCHAR(100),
    BCOMP_TYPE VARCHAR(1),
    BCOMP_MODULE VARCHAR(100),
    BCOMP_MEMO VARCHAR(500),
    BCOMP_RANGE VARCHAR(100),
    BCOMP_TIME_NODE VARCHAR(20),
    BCOMP_STATE VARCHAR(20),
    BCOMP_PARTITION_NUM INT DEFAULT 1,
    BCOMP_DATE_MODE VARCHAR(1),
    BCOMP_SAMPLE_LIMIT INT, -- NULL uses the runtime global fallback; 0 saves summary only
    BCOMP_SHARD_STRATEGY VARCHAR(20)
);
CREATE TABLE TSS_BCOMP_TASK_NEW (
    BCOMP_INDEX BIGINT,
    TASK_BUSI_DATE VARCHAR(8),
    TASK_BATCH VARCHAR(20),
    BCOMP_TIME_NODE VARCHAR(20),
    VERIFY_BUSINESS_DATE VARCHAR(8),
    CREATE_DATETIME VARCHAR(14),
    TASK_STATE VARCHAR(1) NOT NULL DEFAULT '1', -- 1等待、2运行、3完成、4失败、5用户取消
    TASK_RESULT VARCHAR(1),
    BEGIN_DATETIME VARCHAR(14),
    END_DATETIME VARCHAR(14),
    FTASK_REASON VARCHAR(4000),
    FILE1_ACOUNT BIGINT,
    FILE2_ACOUNT BIGINT,
    FILE1_SCOUNT BIGINT,
    FILE2_SCOUNT BIGINT,
    FILE1_FCOUNT BIGINT,
    FILE2_FCOUNT BIGINT,
    BCOMP_READ_MODE VARCHAR(1000),
    PRIMARY KEY (BCOMP_INDEX, TASK_BUSI_DATE, TASK_BATCH)
);
CREATE TABLE TSS_BCOMP_DATABASE_CONFIG_NEW (
    DATABASE_ID BIGINT PRIMARY KEY,
    DATABASE_NAME VARCHAR(200),
    DATABASE_URL VARCHAR(1000),
    DATABASE_USER VARCHAR(100),
    DATABASE_PASSWORD VARCHAR(1000),
    DATABASE_DRIVER VARCHAR(200),
    DATABASE_ENCRYPTION VARCHAR(1),
    DATABASE_GENERATERKEY VARCHAR(200)
);
CREATE TABLE TSS_BCOMP_TABLE_SQL_NEW (
    BCOMP_INDEX BIGINT PRIMARY KEY,
    ORIG_DATABASE_ID BIGINT,
    DEST_DATABASE_ID BIGINT,
    ORIG_SQL TEXT,
    DEST_SQL TEXT
);
CREATE TABLE TSS_BCOMP_FIELD_NEW (
    BCOMP_INDEX BIGINT,
    FIELD_NAME VARCHAR(100),
    FIELD_TYPE VARCHAR(1),
    FIELD_MEMO VARCHAR(500),
    FIELD_OLD_INDEX BIGINT,
    FIELD_NEW_INDEX BIGINT,
    FIELD_INDEX_FLAG VARCHAR(1),
    FIELD_ENUM_FLAG VARCHAR(1),
    FIELD_ENUM_INDEX BIGINT,
    FIELD_PARTITION_FLAG VARCHAR(1),
    FIELD_IGNORE_VALUE VARCHAR(200),
    FIELD_IGNORE_FLAG VARCHAR(1)
);
CREATE TABLE TSS_BCOMP_DTL_NEW (
    BCOMP_INDEX BIGINT,
    TASK_DATE VARCHAR(8),
    TASK_BATCH VARCHAR(20),
    COMP_INDEX_STR VARCHAR(1000),
    LINE_CONTENT1 TEXT,
    LINE_CONTENT2 TEXT,
    LINE_RESULT VARCHAR(1),
    FDTL_REASON VARCHAR(2000)
);

CREATE INDEX idx_bcomp_task_new_state ON TSS_BCOMP_TASK_NEW (TASK_STATE,BCOMP_INDEX);
CREATE INDEX idx_bcomp_task_new_date ON TSS_BCOMP_TASK_NEW (TASK_BUSI_DATE,TASK_STATE);
CREATE INDEX idx_bcomp_field_new_order ON TSS_BCOMP_FIELD_NEW (BCOMP_INDEX,FIELD_OLD_INDEX);
CREATE INDEX idx_bcomp_dtl_new_task ON TSS_BCOMP_DTL_NEW (BCOMP_INDEX,TASK_DATE,TASK_BATCH);
-- 三张规则表：首次创建空表，不复制旧数据。
CREATE TABLE TSS_BCOMP_ENUM_NEW (
    CONV_ENUM_INDEX BIGINT,
    ORIG_ENUM_VALUE VARCHAR(200),
    DEST_ENUM_VALUE VARCHAR(200)
);
CREATE INDEX idx_bcomp_enum_new_id ON TSS_BCOMP_ENUM_NEW (CONV_ENUM_INDEX);

CREATE TABLE TSS_IGNORE_VALUE_NEW (
    IGNORE_ID BIGINT,
    IGNORE_VALUE VARCHAR(200)
);
CREATE INDEX idx_ignore_value_new_id ON TSS_IGNORE_VALUE_NEW (IGNORE_ID);

-- 仅保留当前 Spark 预编译查询需要的字段；当前代码不执行该查询。
CREATE TABLE TSS_BCOMP_DIFFFIELD_NEW (
    BCOMP_INDEX BIGINT
);
CREATE INDEX idx_bcomp_difffield_new_id ON TSS_BCOMP_DIFFFIELD_NEW (BCOMP_INDEX);

-- 批次历史：独立保存提交身份和任务名称，不依赖当前配置存在。

CREATE TABLE TSS_BCOMP_BATCH_NEW (
    BATCH_ID VARCHAR(20) PRIMARY KEY,
    REQUEST_ID VARCHAR(64) NOT NULL UNIQUE,
    REQUEST_HASH VARCHAR(64) NOT NULL,
    TASK_BUSI_DATE VARCHAR(8) NOT NULL,
    VERIFY_BUSINESS_DATE VARCHAR(8),
    SOURCE_BATCH_ID VARCHAR(20),
    CREATED_AT VARCHAR(14) NOT NULL,
    TOTAL_COUNT INT NOT NULL CHECK (TOTAL_COUNT > 0)
);
CREATE INDEX idx_bcomp_batch_new_created ON TSS_BCOMP_BATCH_NEW (CREATED_AT, BATCH_ID);

CREATE TABLE TSS_BCOMP_BATCH_ITEM_NEW (
    BATCH_ID VARCHAR(20) NOT NULL REFERENCES TSS_BCOMP_BATCH_NEW(BATCH_ID),
    BCOMP_INDEX BIGINT NOT NULL,
    CONFIGURATION_NAME VARCHAR(100) NOT NULL,
    CONFIGURATION_MODULE VARCHAR(100),
    TIME_NODE VARCHAR(20) NOT NULL,
    VERIFY_BUSINESS_DATE VARCHAR(8),
    CONFIGURATION_HASH VARCHAR(64) NOT NULL,
    PRIMARY KEY (BATCH_ID, BCOMP_INDEX)
);
CREATE INDEX idx_bcomp_batch_item_new_config ON TSS_BCOMP_BATCH_ITEM_NEW (BCOMP_INDEX, BATCH_ID);

CREATE TABLE TSS_BCOMP_RESULT_NEW (
    BCOMP_INDEX BIGINT NOT NULL,
    RESULT_DATE VARCHAR(8) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    TASK_BUSI_DATE VARCHAR(8) NOT NULL,
    TASK_BATCH VARCHAR(20) NOT NULL,
    TIME_NODE VARCHAR(20) NOT NULL,
    CONFIGURATION_NAME VARCHAR(100),
    CONFIGURATION_MODULE VARCHAR(100),
    ORIGIN_DATABASE_ID BIGINT,
    ORIGIN_DATABASE_NAME VARCHAR(200),
    DESTINATION_DATABASE_ID BIGINT,
    DESTINATION_DATABASE_NAME VARCHAR(200),
    ORIGIN_COUNT BIGINT NOT NULL,
    DESTINATION_COUNT BIGINT NOT NULL,
    MATCHED_COUNT BIGINT NOT NULL,
    ONLY_ORIGIN_COUNT BIGINT NOT NULL,
    ONLY_DESTINATION_COUNT BIGINT NOT NULL,
    DIFFERENT_COUNT BIGINT NOT NULL,
    DETAIL_LIMIT INT NOT NULL,
    ORIGIN_SAMPLES INT NOT NULL,
    DESTINATION_SAMPLES INT NOT NULL,
    DIFFERENT_SAMPLES INT NOT NULL,
    PUBLISHED_AT VARCHAR(14) NOT NULL,
    DETAILS_EXPIRED VARCHAR(1) NOT NULL DEFAULT '0',
    PRIMARY KEY (BCOMP_INDEX,RESULT_DATE),
    CHECK (ORIGIN_COUNT=MATCHED_COUNT+ONLY_ORIGIN_COUNT+DIFFERENT_COUNT),
    CHECK (DESTINATION_COUNT=MATCHED_COUNT+ONLY_DESTINATION_COUNT+DIFFERENT_COUNT)
);
CREATE INDEX idx_bcomp_result_date ON TSS_BCOMP_RESULT_NEW(RESULT_DATE,BCOMP_INDEX);
CREATE INDEX idx_bcomp_result_expiry ON TSS_BCOMP_RESULT_NEW(DETAILS_EXPIRED,PUBLISHED_AT);
CREATE TABLE TSS_BCOMP_FIELD_DIFF_NEW (
    BCOMP_INDEX BIGINT NOT NULL,
    RESULT_DATE VARCHAR(8) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    PATTERN_ID VARCHAR(64) NOT NULL,
    FIELDS_JSON TEXT NOT NULL,
    DIFFERENT_COUNT BIGINT NOT NULL CHECK (DIFFERENT_COUNT > 0),
    SAMPLE_COUNT INT NOT NULL CHECK (SAMPLE_COUNT >= 0),
    COLLAPSED_PATTERN_COUNT INT NOT NULL DEFAULT 1 CHECK (COLLAPSED_PATTERN_COUNT > 0),
    PRIMARY KEY (BCOMP_INDEX,RESULT_DATE,PATTERN_ID)
);
CREATE INDEX idx_bcomp_field_diff_date ON TSS_BCOMP_FIELD_DIFF_NEW(RESULT_DATE,BCOMP_INDEX);

ALTER TABLE TSS_BCOMP_TASK_NEW ADD COLUMN RESULT_DATE VARCHAR(8);
ALTER TABLE TSS_BCOMP_DTL_NEW ADD COLUMN RESULT_DATE VARCHAR(8);
ALTER TABLE TSS_BCOMP_DTL_NEW ADD COLUMN SAMPLE_NO INT;
ALTER TABLE TSS_BCOMP_DTL_NEW ADD COLUMN DETAIL_JSON TEXT;
ALTER TABLE TSS_BCOMP_DTL_NEW ADD COLUMN PATTERN_ID VARCHAR(64);
CREATE UNIQUE INDEX idx_bcomp_dtl_daily_sample ON TSS_BCOMP_DTL_NEW(BCOMP_INDEX,RESULT_DATE,LINE_RESULT,SAMPLE_NO);
CREATE INDEX idx_bcomp_dtl_pattern ON TSS_BCOMP_DTL_NEW(BCOMP_INDEX,RESULT_DATE,LINE_RESULT,PATTERN_ID,SAMPLE_NO);

COMMIT;
