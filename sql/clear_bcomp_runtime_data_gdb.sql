-- 清空 bd 运行数据：任务、批次、每日结果和差异样本。
-- 仅适用于使用 *_NEW 表的 bd 元数据库；会永久删除这些表中的全部记录。
-- 执行前：1. 使用 ./stop.sh 停止 bd 服务；2. 确认 Spark 中没有仍在运行的比对应用；
--         3. 连接 bd 元数据库，并连接与服务配置一致的 GDB schema；4. 按需先备份。
-- 保留：TSS_BCOMP_CONF_NEW、TSS_BCOMP_TABLE_SQL_NEW、TSS_BCOMP_FIELD_NEW、
--       TSS_BCOMP_DATABASE_CONFIG_NEW、TSS_BCOMP_ENUM_NEW、TSS_IGNORE_VALUE_NEW、
--       TSS_BCOMP_DIFFFIELD_NEW；不影响 Axon 工程自己的数据库表。
-- GDB/MySQL TRUNCATE 会隐式提交；脚本按顺序逐表清空，不使用 CASCADE。

START TRANSACTION;

DELETE FROM TSS_BCOMP_FULL_RUN_NEW;

TRUNCATE TABLE TSS_BCOMP_BATCH_ITEM_NEW;
TRUNCATE TABLE TSS_BCOMP_BATCH_NEW;
TRUNCATE TABLE TSS_BCOMP_TASK_NEW;
TRUNCATE TABLE TSS_BCOMP_DTL_NEW;
TRUNCATE TABLE TSS_BCOMP_FIELD_DIFF_NEW;
TRUNCATE TABLE TSS_BCOMP_FIELD_COUNT_NEW;
TRUNCATE TABLE TSS_BCOMP_RESULT_NEW;

COMMIT;

-- 可选验收：执行后应全部为 0；配置与数据库连接应保持原记录数。
SELECT 'TSS_BCOMP_FULL_RUN_NEW' AS table_name, COUNT(*) AS row_count FROM TSS_BCOMP_FULL_RUN_NEW
UNION ALL SELECT 'TSS_BCOMP_FULL_STAGE_NEW', COUNT(*) FROM TSS_BCOMP_FULL_STAGE_NEW
UNION ALL SELECT 'TSS_BCOMP_FULL_WIN_NEW', COUNT(*) FROM TSS_BCOMP_FULL_WIN_NEW
UNION ALL SELECT 'TSS_BCOMP_BATCH_ITEM_NEW', COUNT(*) AS row_count FROM TSS_BCOMP_BATCH_ITEM_NEW
UNION ALL SELECT 'TSS_BCOMP_BATCH_NEW', COUNT(*) FROM TSS_BCOMP_BATCH_NEW
UNION ALL SELECT 'TSS_BCOMP_TASK_NEW', COUNT(*) FROM TSS_BCOMP_TASK_NEW
UNION ALL SELECT 'TSS_BCOMP_DTL_NEW', COUNT(*) FROM TSS_BCOMP_DTL_NEW
UNION ALL SELECT 'TSS_BCOMP_FIELD_DIFF_NEW', COUNT(*) FROM TSS_BCOMP_FIELD_DIFF_NEW
UNION ALL SELECT 'TSS_BCOMP_FIELD_COUNT_NEW', COUNT(*) FROM TSS_BCOMP_FIELD_COUNT_NEW
UNION ALL SELECT 'TSS_BCOMP_RESULT_NEW', COUNT(*) FROM TSS_BCOMP_RESULT_NEW;
