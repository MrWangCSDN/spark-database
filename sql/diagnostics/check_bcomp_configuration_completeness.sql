-- 只读诊断：请连接到 bd 服务实际使用的元数据库和 schema 后执行。
-- 范围包含正常对照 #478~#480 与异常段 #481~#498。
-- 不输出查询 SQL 正文、URL、用户名、密码、密文或加密口令。
-- NULL/空白 BCOMP_DATE_MODE 在当前版本允许；非空只能精确为单字符 1 或 2。
-- CHAR_LENGTH 用于识别 "1 " 等原值；SQL TRIM 检查常见空格，特殊 Unicode 空白仍需结合原值核对。
-- 本语句诊断基础完整性，不尝试连接业务库，不验证密码、驱动加载或 SQL 可执行性。
SELECT
  c.BCOMP_INDEX,
  c.BCOMP_NAME,
  c.BCOMP_STATE,
  CHAR_LENGTH(c.BCOMP_STATE) AS STATE_LENGTH,
  c.BCOMP_DATE_MODE,
  CHAR_LENGTH(c.BCOMP_DATE_MODE) AS DATE_MODE_LENGTH,
  COALESCE(f.FIELD_COUNT, 0) AS FIELD_COUNT,
  COALESCE(sc.SQL_COUNT, 0) AS SQL_COUNT,
  s.ORIG_DATABASE_ID,
  s.DEST_DATABASE_ID,
  o.DATABASE_ID AS ORIG_CONNECTION_ID,
  d.DATABASE_ID AS DEST_CONNECTION_ID,
  CASE
    WHEN NULLIF(TRIM(c.BCOMP_NAME), '') IS NULL THEN '配置名称为空'
    WHEN NULLIF(TRIM(c.BCOMP_STATE), '') IS NULL THEN '配置状态为空'
    WHEN NULLIF(TRIM(c.BCOMP_DATE_MODE), '') IS NOT NULL
      AND (CHAR_LENGTH(c.BCOMP_DATE_MODE) <> 1 OR c.BCOMP_DATE_MODE NOT IN ('1', '2'))
      THEN '日期模式非空且不为1或2'
    ELSE 'OK'
  END AS BASIC_CHECK,
  CASE
    WHEN COALESCE(sc.SQL_COUNT, 0) = 0 THEN '缺少SQL配置行'
    WHEN COALESCE(sc.SQL_COUNT, 0) > 1 THEN 'SQL配置行重复，需逐行检查'
    WHEN NULLIF(TRIM(s.ORIG_SQL), '') IS NULL THEN '源端SQL为空'
    WHEN NULLIF(TRIM(s.DEST_SQL), '') IS NULL THEN '目标端SQL为空'
    ELSE 'OK'
  END AS SQL_CHECK,
  CASE WHEN COALESCE(f.FIELD_COUNT, 0) = 0 THEN '无比对字段' ELSE 'OK' END AS FIELD_CHECK,
  CASE
    WHEN s.ORIG_DATABASE_ID IS NULL THEN '源端连接ID为空'
    WHEN o.DATABASE_ID IS NULL THEN '源端连接ID无对应连接记录'
    WHEN NULLIF(TRIM(o.DATABASE_URL), '') IS NULL THEN '源端URL为空'
    WHEN NULLIF(TRIM(o.DATABASE_USER), '') IS NULL THEN '源端用户名为空'
    WHEN NULLIF(TRIM(o.DATABASE_DRIVER), '') IS NULL THEN '源端驱动类为空'
    ELSE 'OK'
  END AS ORIG_DB_CHECK,
  CASE
    WHEN s.DEST_DATABASE_ID IS NULL THEN '目标端连接ID为空'
    WHEN d.DATABASE_ID IS NULL THEN '目标端连接ID无对应连接记录'
    WHEN NULLIF(TRIM(d.DATABASE_URL), '') IS NULL THEN '目标端URL为空'
    WHEN NULLIF(TRIM(d.DATABASE_USER), '') IS NULL THEN '目标端用户名为空'
    WHEN NULLIF(TRIM(d.DATABASE_DRIVER), '') IS NULL THEN '目标端驱动类为空'
    ELSE 'OK'
  END AS DEST_DB_CHECK
FROM TSS_BCOMP_CONF_NEW c
LEFT JOIN TSS_BCOMP_TABLE_SQL_NEW s ON s.BCOMP_INDEX = c.BCOMP_INDEX
LEFT JOIN (
  SELECT BCOMP_INDEX, COUNT(*) AS SQL_COUNT
  FROM TSS_BCOMP_TABLE_SQL_NEW
  GROUP BY BCOMP_INDEX
) sc ON sc.BCOMP_INDEX = c.BCOMP_INDEX
LEFT JOIN (
  SELECT BCOMP_INDEX, COUNT(*) AS FIELD_COUNT
  FROM TSS_BCOMP_FIELD_NEW
  GROUP BY BCOMP_INDEX
) f ON f.BCOMP_INDEX = c.BCOMP_INDEX
LEFT JOIN TSS_BCOMP_DATABASE_CONFIG_NEW o ON o.DATABASE_ID = s.ORIG_DATABASE_ID
LEFT JOIN TSS_BCOMP_DATABASE_CONFIG_NEW d ON d.DATABASE_ID = s.DEST_DATABASE_ID
WHERE c.BCOMP_TYPE = '2'
  AND c.BCOMP_INDEX BETWEEN 478 AND 498
ORDER BY c.BCOMP_INDEX;
