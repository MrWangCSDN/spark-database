-- 只读补查：请在 bd 服务实际使用的元数据库/schema 中执行下面三条 SELECT。
-- 500倍数仅提示字段批次中断，不能证明中断，更不能证明480应有多少字段。
-- 480及其他表的预期字段必须与原始Axon导出SQL/同版本快照逐条比对。
-- 不输出字段备注、查询SQL、连接信息、密码或密文。
SELECT
  COUNT(*) AS TOTAL_FIELD_COUNT,
  MOD(COUNT(*), 500) AS FIELD_COUNT_MOD_500,
  MIN(BCOMP_INDEX) AS MIN_FIELD_BCOMP_INDEX,
  MAX(BCOMP_INDEX) AS MAX_FIELD_BCOMP_INDEX
FROM TSS_BCOMP_FIELD_NEW;

SELECT
  c.BCOMP_INDEX,
  c.BCOMP_NAME,
  COALESCE(f.FIELD_COUNT, 0) AS FIELD_COUNT,
  f.MIN_OLD_POSITION,
  f.MAX_OLD_POSITION,
  f.MIN_NEW_POSITION,
  f.MAX_NEW_POSITION,
  COALESCE(f.KEY_FIELD_COUNT, 0) AS KEY_FIELD_COUNT
FROM TSS_BCOMP_CONF_NEW c
LEFT JOIN (
  SELECT BCOMP_INDEX,
    COUNT(*) AS FIELD_COUNT,
    MIN(FIELD_OLD_INDEX) AS MIN_OLD_POSITION,
    MAX(FIELD_OLD_INDEX) AS MAX_OLD_POSITION,
    MIN(FIELD_NEW_INDEX) AS MIN_NEW_POSITION,
    MAX(FIELD_NEW_INDEX) AS MAX_NEW_POSITION,
    SUM(CASE WHEN FIELD_INDEX_FLAG = '1' THEN 1 ELSE 0 END) AS KEY_FIELD_COUNT
  FROM TSS_BCOMP_FIELD_NEW
  GROUP BY BCOMP_INDEX
) f ON f.BCOMP_INDEX = c.BCOMP_INDEX
WHERE c.BCOMP_TYPE = '2'
ORDER BY c.BCOMP_INDEX;

SELECT BCOMP_INDEX, FIELD_NAME, FIELD_OLD_INDEX, FIELD_NEW_INDEX, FIELD_INDEX_FLAG
FROM TSS_BCOMP_FIELD_NEW
WHERE BCOMP_INDEX BETWEEN 478 AND 498
ORDER BY BCOMP_INDEX, FIELD_OLD_INDEX, FIELD_NEW_INDEX, FIELD_NAME;
